    metadata = _read_plugin_metadata(plugin_dir / "metadata.txt")

    plugin_name = metadata.get("name", "BDOT10k_GML_SHP")
    version = metadata.get("version", "")
    repository = metadata.get(
        "repository",
        "https://github.com/GlownyUrzadGeodezjiIKartografii/BDOT10k_GML_SHP",
    )
    tracker = metadata.get(
        "tracker",
        repository.rstrip("/") + "/issues",
    )
    documentation = metadata.get(
        "homepage",
        repository,
    ).rstrip("/") + "#readme"

    dialog = QDialog(parent)
    dialog.setProperty("BDOT10k_GML_SHP_Loader_window", True)
    dialog.setWindowTitle("Informacje")
    dialog.setModal(True)
    dialog.resize(600, 450)
    dialog.setMinimumSize(560, 420)

    # Układ celowo nawiązuje do zakładki „Informacje” z Walidatora plików GML:
    # duże pole z parametrami w dwóch kolumnach, logo w lewym dolnym rogu

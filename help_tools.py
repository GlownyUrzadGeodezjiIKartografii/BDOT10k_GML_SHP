def _show_bdot10k_wms(parent, iface, service_url, group_name, display_name):
    """Pobierz GetCapabilities wskazanej usługi i dodaj jej warstwy do projektu QGIS."""
    project = QgsProject.instance()

    existing_layers = [
        layer
        for layer in project.mapLayers().values()
        if layer.providerType() == "wms" and service_url in layer.source()
    ]
    if existing_layers:
        for layer in existing_layers:
            node = project.layerTreeRoot().findLayer(layer.id())
            if node is not None:
                node.setItemVisibilityChecked(True)
        iface.messageBar().pushInfo(
            "BDOT10k",
            f"Mapa „{display_name}” jest już dodana do projektu.",
        )
        return

    progress = QProgressDialog(
        "Pobieranie informacji o usłudze WMS…",
        "Anuluj",
        0,
        0,
        parent,
    )
    progress.setWindowTitle(display_name)
    progress.setMinimumDuration(0)
    progress.setAutoClose(False)
    progress.show()

    capabilities_url = service_url + "?SERVICE=WMS&REQUEST=GetCapabilities"
    request = QNetworkRequest(QUrl(capabilities_url))

    # W nowszych wersjach Qt jawnie zezwalamy na bezpieczne przekierowania.
    try:
        request.setAttribute(
            QNetworkRequest.RedirectPolicyAttribute,
            QNetworkRequest.NoLessSafeRedirectPolicy,
        )
    except AttributeError:
        try:
            request.setAttribute(QNetworkRequest.FollowRedirectsAttribute, True)
        except AttributeError:
            pass

    reply = QgsNetworkAccessManager.instance().get(request)
    loop = QEventLoop()
    reply.finished.connect(loop.quit)
    progress.canceled.connect(reply.abort)
    loop.exec_()
    progress.close()

    if reply.error() != QNetworkReply.NoError:
        error_text = reply.errorString()
        reply.deleteLater()
        if error_text.lower() == "operation canceled":
            return
        QMessageBox.critical(
            parent,
            "BDOT10k",
            f"Nie udało się odczytać usługi „{display_name}”.\n\n{error_text}",
        )
        return

    capabilities = bytes(reply.readAll())
    reply.deleteLater()

    layer_specs = _parse_wms_capabilities(capabilities, project.crs().authid())
    if not layer_specs:
        QMessageBox.critical(
            parent,
            "BDOT10k",
            "Usługa WMS nie zwróciła żadnej warstwy możliwej do wyświetlenia.",
        )
        return

    root = project.layerTreeRoot()
    group = root.findGroup(group_name)
    if group is None:
        group = root.insertGroup(0, group_name)

    added_layers = []
    failed_titles = []
    # Dodawanie od końca zachowuje kolejność z GetCapabilities w drzewie warstw.
    for name, title, crs in reversed(layer_specs):
        source = (
            f"url={service_url}"
            f"&layers={name}"
            "&styles="
            "&format=image/png"
            f"&crs={crs}"
        )
        layer = QgsRasterLayer(source, title, "wms")
        if not layer.isValid():
            failed_titles.append(title)
            continue

        project.addMapLayer(layer, False)
        group.insertLayer(0, layer)
        added_layers.append(layer)

    if not added_layers:
        QMessageBox.critical(
            parent,
            "BDOT10k",
            f"Nie udało się utworzyć warstwy WMS „{display_name}”.",
        )
        return

    group.setExpanded(True)
    iface.messageBar().pushSuccess(
        "BDOT10k",
        f"Dodano mapę „{display_name}” z usługi Geoportalu.",
    )

    if failed_titles:
        QMessageBox.warning(
            parent,
            "BDOT10k",
            "Część warstw usługi WMS nie mogła zostać wczytana:\n\n"
            + "\n".join(f"• {title}" for title in failed_titles),
        )


def _parse_wms_capabilities(xml_bytes, project_crs):
    """Zwróć listę (nazwa, tytuł, CRS) dla nazwanych warstw liściowych WMS."""
    document = QDomDocument()
    result = document.setContent(xml_bytes)
    ok = result[0] if isinstance(result, tuple) else bool(result)
    if not ok:
        return []

    nodes = document.elementsByTagName("Layer")
    all_named = []
    leaf_named = []

    for index in range(nodes.count()):
        element = nodes.at(index).toElement()
        if element.isNull():
            continue

        name = element.firstChildElement("Name").text().strip()
        if not name:
            continue
        title = element.firstChildElement("Title").text().strip() or name
        crs = _choose_layer_crs(element, project_crs)
        if not crs:
            continue

        spec = (name, title, crs)
        all_named.append(spec)
        if element.firstChildElement("Layer").isNull():
            leaf_named.append(spec)

    return leaf_named or all_named


def _choose_layer_crs(layer_element, project_crs):
    """Wybierz CRS obsługiwany przez warstwę, uwzględniając dziedziczenie WMS."""
    available = []
    current = layer_element

    while not current.isNull():
        child = current.firstChild()
        while not child.isNull():
            child_element = child.toElement()
            if not child_element.isNull() and child_element.tagName() in ("CRS", "SRS"):
                for value in child_element.text().split():
                    if value and value not in available:
                        available.append(value)
            child = child.nextSibling()

        parent = current.parentNode().toElement()
        if parent.isNull() or parent.tagName() != "Layer":
            break
        current = parent

    preferred = [project_crs, "EPSG:2180", "EPSG:3857", "EPSG:4326"]
    for crs in preferred:
        if crs and crs in available:
            return crs
    return available[0] if available else "EPSG:2180"


def _safe_unlink(path):
    """Usuń plik pomocniczy bez zgłaszania błędu przy sprzątaniu po operacji."""
    try:
        if path.exists():
            path.unlink()
    except OSError:
        pass
